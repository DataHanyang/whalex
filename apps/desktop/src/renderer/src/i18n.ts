// English-first: unless the user explicitly picks a locale, default to English.
function resolve(language: "system" | "ko" | "en"): string {
  if (language === "ko" || language === "en") return language;
  // "system" respects the OS only for locales we ship; otherwise English.
  return navigator.language.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function initI18n(language: "system" | "ko" | "en"): void {
  void i18n.use(initReactI18next).init({
    resources: { en, ko },
    lng: resolve(language),
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });
}

export function switchLanguage(language: "system" | "ko" | "en"): void {
  void i18n.changeLanguage(resolve(language));
}
