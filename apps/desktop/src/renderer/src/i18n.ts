/** Every shipped locale, labelled in its own language — pickers render this. */
export const LANGUAGES: Array<[Exclude<AppLanguage, "system">, string]> = [
  ["en", "English"],
  ["ko", "한국어"],
  ["zh", "简体中文"],
  ["zh-TW", "繁體中文"],
  ["ja", "日本語"],
  ["fr", "Français"],
  ["de", "Deutsch"],
  ["ru", "Русский"],
  ["vi", "Tiếng Việt"],
  ["th", "ไทย"],
  ["id", "Bahasa Indonesia"],
];

// English-first: unless the user explicitly picks a locale, default to English.
function resolve(language: AppLanguage): string {
  return language === "system" ? resolveSystemLanguage(navigator.language) : language;
}

export function initI18n(language: AppLanguage): void {
  void i18n.use(initReactI18next).init({
    resources: { en, ko, zh, "zh-TW": zhTW, ja, fr, de, ru, vi, th, id },
    lng: resolve(language),
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });
}

export function switchLanguage(language: AppLanguage): void {
  void i18n.changeLanguage(resolve(language));
}
